from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

REQUIRED_SUMMARY_KEYS = [
    "loaded_frames",
    "spawned_vehicle_count",
    "off_lane_vehicle_count",
    "max_off_lane_distance_m",
    "lane_count",
    "rendered_lane_count",
    "rendered_junction_count",
]


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Build a render bridge quality report from a Godot SUMO replay_summary.json. "
            "This is a lightweight QA layer over the existing replay smoke output."
        )
    )
    parser.add_argument(
        "--replay-summary",
        required=True,
        help="Path to replay_summary.json generated by godot_sumo_trace_replay_smoke.py.",
    )
    parser.add_argument("--out-json", required=True, help="Output quality report JSON path.")
    parser.add_argument("--out-md", default=None, help="Optional Markdown report path.")
    return parser


def load_summary(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _int_value(payload: dict[str, Any], key: str) -> int:
    value = payload.get(key, 0)
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        return int(value)
    if isinstance(value, str) and value.strip():
        return int(float(value))
    return 0


def _float_value(payload: dict[str, Any], key: str) -> float:
    value = payload.get(key, 0.0)
    if isinstance(value, bool):
        return float(value)
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, str) and value.strip():
        return float(value)
    return 0.0


def build_quality_report(summary: dict[str, Any]) -> dict[str, Any]:
    warnings: list[str] = []
    missing_keys = [key for key in REQUIRED_SUMMARY_KEYS if key not in summary]
    for key in missing_keys:
        warnings.append(f"missing_summary_key:{key}")

    zone_overlay = summary.get("zone_overlay", {})
    if not isinstance(zone_overlay, dict):
        zone_overlay = {}
        warnings.append("zone_overlay_not_object")

    if _int_value(summary, "off_lane_vehicle_count") > 0:
        warnings.append("vehicles_outside_sumo_lane_geometry")
    if _int_value(summary, "vehicle_fallback_spawn_count") > 0:
        warnings.append("vehicle_asset_fallback_used")
    if _int_value(zone_overlay, "fallback_zone_count") > 0:
        warnings.append("zone_asset_fallback_used")
    if _int_value(summary, "lane_count") > 0 and _int_value(summary, "rendered_lane_count") <= 0:
        warnings.append("sumo_lanes_loaded_but_not_rendered")

    quality_passed = not warnings
    return {
        "schema_version": "render_bridge_quality_report.v1",
        "quality_passed": quality_passed,
        "warnings": warnings,
        "geometry": {
            "lane_count": _int_value(summary, "lane_count"),
            "road_count": _int_value(summary, "road_count"),
            "intersection_count": _int_value(summary, "intersection_count"),
            "rendered_lane_count": _int_value(summary, "rendered_lane_count"),
            "rendered_junction_count": _int_value(summary, "rendered_junction_count"),
            "lane_render_model": summary.get("lane_render_model", ""),
            "sumo_geometry_data_model": summary.get("sumo_geometry_data_model", ""),
        },
        "vehicles": {
            "loaded_frames": _int_value(summary, "loaded_frames"),
            "spawned_vehicle_count": _int_value(summary, "spawned_vehicle_count"),
            "largest_active_vehicle_count": _int_value(summary, "largest_active_vehicle_count"),
            "vehicle_scene_count": _int_value(summary, "vehicle_scene_count"),
            "vehicle_fallback_spawn_count": _int_value(summary, "vehicle_fallback_spawn_count"),
            "vehicle_pool_model": summary.get("vehicle_pool_model", ""),
        },
        "alignment": {
            "off_lane_vehicle_count": _int_value(summary, "off_lane_vehicle_count"),
            "max_off_lane_distance_m": _float_value(summary, "max_off_lane_distance_m"),
        },
        "zones": {
            "spawned_zone_count": _int_value(zone_overlay, "spawned_zone_count"),
            "fallback_zone_count": _int_value(zone_overlay, "fallback_zone_count"),
            "registered_zone_type_count": _int_value(zone_overlay, "registered_zone_type_count"),
        },
        "traffic_lights": {
            "traffic_light_sync_count": _int_value(summary, "traffic_light_sync_count"),
        },
        "source_summary": {
            "trace_schema_version": summary.get("trace_schema_version", ""),
            "vehicle_asset_catalog_path": summary.get("vehicle_asset_catalog_path", ""),
            "caveat": summary.get("caveat", ""),
        },
    }


def markdown_report(report: dict[str, Any]) -> str:
    status = "PASS" if report["quality_passed"] else "WARN"
    warnings = report.get("warnings", [])
    lines = [
        "# Render bridge quality report",
        "",
        f"Status: `{status}`",
        "",
        "## Geometry",
        "",
        f"- lanes: {report['geometry']['lane_count']}",
        f"- rendered lanes: {report['geometry']['rendered_lane_count']}",
        f"- rendered junctions: {report['geometry']['rendered_junction_count']}",
        "",
        "## Vehicles",
        "",
        f"- loaded frames: {report['vehicles']['loaded_frames']}",
        f"- spawned vehicles: {report['vehicles']['spawned_vehicle_count']}",
        f"- fallback vehicle spawns: {report['vehicles']['vehicle_fallback_spawn_count']}",
        "",
        "## Alignment",
        "",
        f"- off-lane vehicles: {report['alignment']['off_lane_vehicle_count']}",
        f"- max off-lane distance m: {report['alignment']['max_off_lane_distance_m']}",
        "",
        "## Warnings",
        "",
    ]
    if warnings:
        lines.extend(f"- `{warning}`" for warning in warnings)
    else:
        lines.append("- none")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    replay_summary = Path(args.replay_summary).resolve()
    out_json = Path(args.out_json).resolve()
    out_md = Path(args.out_md).resolve() if args.out_md else None

    summary = load_summary(replay_summary)
    report = build_quality_report(summary)

    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if out_md is not None:
        out_md.parent.mkdir(parents=True, exist_ok=True)
        out_md.write_text(markdown_report(report), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
