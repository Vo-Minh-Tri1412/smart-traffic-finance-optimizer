from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from ai_quantum_hvtc.sensors import (  # noqa: E402
    init_synthetic_yolo_dataset,
    validate_synthetic_yolo_dataset,
)

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

DEFAULT_OUTPUT_ROOT = PROJECT_ROOT / "data" / "processed" / "cv_yolo"
DEFAULT_GODOT_PROJECT = PROJECT_ROOT / "render"
GODOT_SCRIPT = "res://scripts/dataset_export/export_synthetic_cv_smoke.gd"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Run a tiny Godot synthetic-camera smoke export into the project YOLO dataset "
            "contract. This generates a few PNG frames and YOLO labels only; it does not train."
        )
    )
    parser.add_argument("--dataset-id", default="SYNTH-CV-GODOT-SMOKE")
    parser.add_argument("--output-root", default=str(DEFAULT_OUTPUT_ROOT))
    parser.add_argument("--dataset-root", default=None)
    parser.add_argument("--godot-project", default=str(DEFAULT_GODOT_PROJECT))
    parser.add_argument("--godot-exe", default=None)
    parser.add_argument("--width", type=int, default=640)
    parser.add_argument("--height", type=int, default=640)
    parser.add_argument(
        "--force",
        action="store_true",
        help="Allow reusing an existing dataset folder when initializing the smoke template.",
    )
    return parser


def find_godot_executable(explicit: str | None = None) -> Path | None:
    candidates: list[str | None] = [
        explicit,
        os.environ.get("GODOT_STANDARD_EXE"),
        os.environ.get("GODOT_NET_EXE"),
        shutil.which("godot"),
        shutil.which("godot4"),
    ]
    candidates.extend(
        [
            "D:/GoDot/Godot_v4.6.2-stable_win64_console.exe",
            "D:/Godot/Godot_v4.6.2-stable_win64_console.exe",
            "D:/Godot/Godot_v4.6.2-stable_win64.exe",
            "D:/GoDot/Godot_v4.6.2-stable_mono_win64/Godot_v4.6.2-stable_mono_win64_console.exe",
            "D:/Godot/Godot_v4.6.2-stable_mono_win64/Godot_v4.6.2-stable_mono_win64_console.exe",
        ]
    )
    for candidate in candidates:
        if not candidate:
            continue
        path = Path(candidate)
        if path.is_file():
            return path.resolve()
    return None


def _resolve_dataset_root(args: argparse.Namespace) -> Path:
    if args.dataset_root:
        return Path(args.dataset_root).resolve()
    return (Path(args.output_root) / args.dataset_id).resolve()


def _update_dataset_manifest(dataset_root: Path) -> None:
    manifest_path = dataset_root / "dataset_manifest.json"
    if not manifest_path.is_file():
        return
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["status"] = "smoke_frames_generated"
    manifest["frame_count"] = 2
    manifest["notes"] = (
        "Smoke dataset generated by Godot to verify PNG/YOLO label plumbing. "
        "It is not a final training dataset."
    )
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def run_godot_smoke_export(
    *,
    godot_exe: Path,
    godot_project: Path,
    dataset_root: Path,
    dataset_id: str,
    width: int,
    height: int,
) -> subprocess.CompletedProcess[str]:
    command = [
        str(godot_exe),
        "--headless",
        "--path",
        str(godot_project),
        "--script",
        GODOT_SCRIPT,
        "--",
        "--dataset-root",
        dataset_root.as_posix(),
        "--dataset-id",
        dataset_id,
        "--width",
        str(width),
        "--height",
        str(height),
    ]
    return subprocess.run(  # noqa: S603
        command,
        cwd=PROJECT_ROOT,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    dataset_root = _resolve_dataset_root(args)
    godot_project = Path(args.godot_project).resolve()
    godot_exe = find_godot_executable(args.godot_exe)

    if godot_exe is None:
        print("[FAIL] Godot executable not found. Pass --godot-exe or set GODOT_STANDARD_EXE.")
        return 1
    if not godot_project.is_dir():
        print(f"[FAIL] Godot project not found: {godot_project}")
        return 1

    init_synthetic_yolo_dataset(
        dataset_id=args.dataset_id,
        output_root=dataset_root.parent,
        force=args.force,
        render_id="GODOT-SMOKE-001",
        source_run_id="manual-smoke-static-scene",
    )

    completed = run_godot_smoke_export(
        godot_exe=godot_exe,
        godot_project=godot_project,
        dataset_root=dataset_root,
        dataset_id=args.dataset_id,
        width=args.width,
        height=args.height,
    )
    print(completed.stdout.strip())
    if completed.returncode != 0:
        print(f"[FAIL] Godot smoke export failed with exit code {completed.returncode}")
        return completed.returncode

    _update_dataset_manifest(dataset_root)
    result = validate_synthetic_yolo_dataset(dataset_root)
    for warning in result.warnings:
        print(f"[WARN] {warning}")
    if result.errors:
        for error in result.errors:
            print(f"[FAIL] {error}")
        return 1

    print(f"[OK] Godot synthetic CV smoke dataset valid: {dataset_root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
